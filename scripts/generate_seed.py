"""Generate Supabase seed.sql from the checked-in CSVs, using only Python's standard library."""

import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "supabase" / "seed"


def rows(name):
    with (SEED / f"{name}.csv").open(encoding="utf-8-sig", newline="") as source:
        return list(csv.DictReader(source))


def literal(value):
    return "NULL" if value is None or value == "" else "'" + str(value).replace("'", "''") + "'"


def values(items):
    return ",\n".join("  (" + ", ".join(literal(v) for v in row) + ")" for row in items)


def insert_values(table, columns, items, casts=None):
    casts = casts or {}
    expressions = [f"v.{col}{casts.get(col, '')}" for col in columns]
    return (
        f"INSERT INTO public.{table} ({', '.join(columns)})\n"
        f"SELECT {', '.join(expressions)} FROM (VALUES\n{values(items)}\n) "
        f"AS v({', '.join(columns)});\n"
    )


brands = rows("brands")
cities = rows("cities")
areas = rows("areas")
models = rows("models")
aliases = rows("aliases")
variants = rows("variants")
colors = rows("colors")
content = rows("content_blocks")
settings = rows("app_settings")

# The dependent CSVs identify models by slug alone, so ambiguous input is unsafe.
if len({r["slug"].lower() for r in models}) != len(models):
    raise ValueError("Model slugs must be globally unique in seed CSVs")
model_slugs = {r["slug"].lower() for r in models}
for dataset in (aliases, variants, colors):
    if any(r["model_slug"].lower() not in model_slugs for r in dataset):
        raise ValueError("A seed row refers to a missing model")

parts = ["-- Generated by scripts/generate_seed.py from supabase/seed/*.csv. Do not edit directly.\n"]
parts.append(insert_values("brands", ["id", "name", "slug", "sort_order"],
                           [(r["id"], r["name"], r["slug"], r["sort_order"]) for r in brands],
                           {"id": "::integer", "sort_order": "::integer"}))
parts.append("SELECT setval(pg_get_serial_sequence('public.brands', 'id'), (SELECT max(id) FROM public.brands));\n")
parents = [(r["slug"], r["parent_slug"]) for r in brands if r["parent_slug"]]
parts.append("UPDATE public.brands b SET parent_brand_id = parent.id FROM (VALUES\n" + values(parents) +
             "\n) AS v(slug, parent_slug) JOIN public.brands parent ON parent.slug::text = v.parent_slug WHERE b.slug::text = v.slug;\n")
parts.append(insert_values("cities", ["name_en", "name_ur", "slug", "province", "is_major", "sort_order"],
                           [(r["name_en"], r["name_ur"], r["slug"], r["province"], r["is_major"], r["sort_order"]) for r in cities],
                           {"is_major": "::boolean", "sort_order": "::integer"}))
parts.append("INSERT INTO public.areas (city_id, name_en, name_ur, slug) SELECT c.id, v.name_en, v.name_ur, v.slug FROM (VALUES\n" +
             values([(r["city_slug"], r["name_en"], r["name_ur"], r["slug"]) for r in areas]) +
             "\n) AS v(city_slug, name_en, name_ur, slug) JOIN public.cities c ON c.slug = v.city_slug;\n")

series = sorted({(r["brand_slug"], r["series"], re.sub(r"[^a-z0-9]+", "-", r["series"].lower()).strip("-")) for r in models})
if len({(b, slug) for b, _, slug in series}) != len(series):
    raise ValueError("Series slugs collide within a brand")
parts.append("INSERT INTO public.series (brand_id, name, slug) SELECT b.id, v.name, v.slug FROM (VALUES\n" + values(series) +
             "\n) AS v(brand_slug, name, slug) JOIN public.brands b ON b.slug::text = v.brand_slug;\n")
parts.append("INSERT INTO public.models (brand_id, series_id, name, slug, release_year, supports_battery_health, popularity) "
             "SELECT b.id, s.id, v.name, v.slug, v.release_year::smallint, v.supports_battery_health::boolean, v.popularity::integer FROM (VALUES\n" +
             values([(r["brand_slug"], r["series"], r["name"], r["slug"], r["release_year"], r["supports_battery_health"], r["popularity"]) for r in models]) +
             "\n) AS v(brand_slug, series_name, name, slug, release_year, supports_battery_health, popularity) "
             "JOIN public.brands b ON b.slug::text = v.brand_slug JOIN public.series s ON s.brand_id = b.id AND s.name = v.series_name;\n")

for table, dataset, cols, select in [
    ("model_aliases", aliases, ["alias"], "v.alias"),
    ("model_variants", variants, ["ram_gb", "storage_gb"], "v.ram_gb::smallint, v.storage_gb::smallint"),
    ("model_colors", colors, ["name", "hex"], "v.name, v.hex"),
]:
    parts.append(f"INSERT INTO public.{table} (model_id, {', '.join(cols)}) SELECT m.id, {select} FROM (VALUES\n" +
                 values([(r["model_slug"], *(r[c] for c in cols)) for r in dataset]) +
                 f"\n) AS v(model_slug, {', '.join(cols)}) JOIN public.models m ON m.slug::text = v.model_slug;\n")

parts.append(insert_values("content_blocks", ["key", "body_en", "body_ur"],
                           [(r["key"], r["body_en"], r["body_ur"]) for r in content]))
parts.append(insert_values("app_settings", ["key", "value"],
                           [(r["key"], json.dumps(json.loads(r["value"]), ensure_ascii=False)) for r in settings],
                           {"value": "::jsonb"}))

# Catch missing FK joins instead of silently publishing incomplete seed data.
expected = {"brands": len(brands), "cities": len(cities), "areas": len(areas), "series": len(series),
            "models": len(models), "model_aliases": len(aliases), "model_variants": len(variants),
            "model_colors": len(colors), "content_blocks": len(content), "app_settings": len(settings)}
parts.append("DO $$ BEGIN\n" + "\n".join(
    f"  IF (SELECT count(*) FROM public.{table}) <> {count} THEN RAISE EXCEPTION 'Seed count mismatch: {table}'; END IF;"
    for table, count in expected.items()) + "\nEND $$;\n")

(ROOT / "supabase" / "seed.sql").write_text("\n".join(parts), encoding="utf-8", newline="\n")
print("Generated supabase/seed.sql:", expected)
